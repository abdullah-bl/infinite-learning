const dictionaries: Record<Lang, Record<Key, string>> = { en, ar };

export type T = (key: Key, vars?: Record<string, string | number>) => string;

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>) {
  let text: string = dictionaries[lang][key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v));
  return text;
}

/** The interface language, a `t` function for it, and the writing direction. */
export function useI18n() {
  const { ui } = useSettings();
  const t: T = (key, vars) => translate(ui, key, vars);
  return { t, lang: ui, dir: ui === "ar" ? ("rtl" as const) : ("ltr" as const) };
}

/** The message for a failed backend call. The backend sends codes; this words them. */
export function errorText(err: unknown, t: T): string {
  const data = (err as { data?: unknown } | null)?.data;
  if (data && typeof data === "object" && "code" in data) {
    const d = data as { code: string; kind?: string; [k: string]: unknown };
    const key = d.code === "rate" ? `err.rate_${d.kind}` : `err.${d.code}`;
    if (key in en) return t(key as Key, d as Record<string, string | number>);
  }
  return t("err.generic");
}

/** The message for a course the backend could not write (`course.error` is a short code). */
export function courseError(code: string | undefined, t: T): string {
  const key = `e.${code}`;
  return code && key in en ? t(key as Key) : t("err.generic");
}
